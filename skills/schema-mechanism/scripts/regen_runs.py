#!/usr/bin/env python3
"""Regenerate the example RUN.md transcripts from their scenarios.

    python3 regen_runs.py            # rewrite every RUN.md under censors/examples
    python3 regen_runs.py --check    # exit 1 if any is stale (for CI or a pre-commit hook)

Timings are left out of the sweep headers so a rerun on another machine
changes nothing unless the model's output does."""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import censor_sim as cs  # noqa: E402

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "censors", "examples")
SINGLE = [("dentist-letter", ["dentist-letter.answers.yml"]), ("beekeepers", []), ("emperors-new-clothes", [])]
BARON = ["loyal-friend", "fan", "ironist", "crusader", "convert", "ironic-crusader", "stage"]


def untimed(text):
    return re.sub(r" in [\d.]+s \([\d,]+/s\)", "", text)


def sweep_text(spec, n):
    s = cs.sweep(spec, n)
    lines = [f"{n} perturbations (±{s['spread']:.0%}), seed {s['seed']}: {s['simulations']} simulations"]
    for k, v in s["runs"].items():
        lines.append(f"run {k}:")
        lines += [f"  fit {f}: {share:.1%}" for f, share in v["fit"].items()]
        lines += [f"  {o['share']:6.1%}  " + " → ".join(map(str, o["choices"])) for o in v["outcomes"]]
    return "\n".join(lines)


def ablate_text(spec):
    return "\n".join(f"{x['run']}: without {x['censor']:<26} {x['fit_without']} (all: {x['fit_with']})  "
                     f"{'needed' if x['needed'] else 'NOT NEEDED'}" for x in cs.ablate(spec))


def single(name, layers):
    path = os.path.join(HERE, name + ".yml")
    spec = cs.load([path], [os.path.join(HERE, x) for x in layers])
    flag = "".join(f" --layer {x}" for x in layers)
    body = cs.render_text([cs.result_of(r, m) for r, m in cs.run(spec)], True)
    return (f"# {name} — run output\n\nGenerated by `censor_sim.py run {name}.yml{flag} --format md`, "
            f"`ablate` and `sweep --n 2000` (via `scripts/regen_runs.py`). Regenerate, don't edit.\n\n"
            f"{body}\n\n```\n{ablate_text(spec)}\n```\n\n```\n{sweep_text(spec, 2000)}\n```\n")


def baron():
    out = ["# The Baron's crowd — generated output\n",
           "Generated by `censor_sim.py` (via `scripts/regen_runs.py`) from the files in this directory. "
           "Fiction: see [`case.yml`](case.yml) and [`stage.yml`](stage.yml). What it means: "
           "[`../../BRAINBALL.md`](../../BRAINBALL.md#the-barons-crowd).\n"]
    for name in BARON:
        spec = cs.load([os.path.join(HERE, "baron", name + ".yml")])
        body = cs.render_text([cs.result_of(r, m) for r, m in cs.run(spec)], True)
        out.append(re.sub(r"^## ", "### ", body, flags=re.M))
        out.append(f"\n**Ablation**\n\n```\n{ablate_text(spec)}\n```\n")
        out.append(f"**Sweep** (1,000 weightings, ±50%)\n\n```\n{sweep_text(spec, 1000)}\n```\n")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    stale = []
    targets = [(os.path.join(HERE, n + ".RUN.md"), lambda n=n, l=l: single(n, l)) for n, l in SINGLE]
    targets.append((os.path.join(HERE, "baron", "RUN.md"), baron))
    for path, make in targets:
        text = untimed(make())
        old = open(path).read() if os.path.exists(path) else ""
        if text != old:
            stale.append(os.path.relpath(path))
            if not check:
                with open(path, "w") as f:
                    f.write(text)
    print(("stale: " if check else "rewrote: ") + (", ".join(stale) or "none"))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
